module mod_functions_and_tasks (
    input logic [7:0] data_in_a,
    input logic [7:0] data_in_b,
    input logic [7:0] data_in_c,
    input logic sel_func,
    input logic sel_task,
    output logic [7:0] func_out,
    output logic [7:0] task_out,
    output logic [7:0] combined_out
);
    function automatic logic [7:0] my_deep_func(logic [7:0] p_a, logic [7:0] p_b, logic [7:0] p_c);
        logic [7:0] temp1, temp2, temp3;
        temp1 = (((p_a + p_b) ^ p_c) & 8'hAA) | ((p_a - p_c) + p_b);
        temp2 = temp1 * 2 + (p_a + p_b) - p_c + (temp1 & (p_a | p_b));
        temp3 = (temp2 == 8'hFF) ? (p_a + p_c) : (p_b - p_a);
        return (temp3 + (temp1 ^ temp2) - p_a);
    endfunction
    task automatic my_complex_task(input logic [7:0] t_in1, input logic [7:0] t_in2, output logic [7:0] t_out);
        logic [7:0] l_temp;
        if (t_in1 > t_in2) begin
            l_temp = t_in1 + t_in2 + 8'd10;
        end else begin
            l_temp = t_in1 - t_in2 - 8'd5;
        end
        t_out = my_deep_func(l_temp, t_in1, t_in2);
    endtask
    always_comb begin
        func_out = my_deep_func(data_in_a, data_in_b, data_in_c);
        if (sel_task) begin
            my_complex_task(data_in_b, data_in_c, task_out);
        end else begin
            task_out = 8'h00;
        end
        combined_out = (sel_func ? func_out : 8'h0) + (sel_task ? task_out : 8'h0);
    end
endmodule
module mod_classes_nonstatic (
    input logic clk,
    input logic rst_n,
    input logic enable_op,
    input int    op_data_in,
    output int   op_data_out,
    output logic is_active_flag
);
    class MyClass;
        rand int m_value;
        int m_offset;
        function new();
            m_value = 0;
            m_offset = 10;
        endfunction
        function automatic void set_value(int val);
            m_value = val + m_offset;
        endfunction
        function automatic int get_value();
            return m_value;
        endfunction
        function automatic int modify_and_get(int input_val);
            set_value(input_val * 2);
            return get_value() + 1;
        endfunction
        function automatic int perform_deep_operation(int a, int b, int c);
            int temp_val;
            temp_val = (m_value + (a * (b - (c + m_offset)))) | ((a & b) ^ c);
            return temp_val;
        endfunction
    endclass
    MyClass my_instance;
    initial begin
        my_instance = new();
    end
    always_ff @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            op_data_out = 0;
            is_active_flag = 1'b0;
            my_instance.set_value(0);
        end else begin
            int local_result;
            is_active_flag = enable_op;
            if (enable_op) begin
                my_instance.set_value(op_data_in);
                local_result = my_instance.modify_and_get(op_data_in + 5);
                op_data_out = my_instance.perform_deep_operation(local_result, op_data_in, my_instance.m_offset);
            end else begin
                op_data_out = my_instance.get_value() - 1;
            end
        end
    end
endmodule
