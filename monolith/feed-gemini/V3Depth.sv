module mod_stmt_types (
    input logic [3:0] select_op,
    input logic [7:0] operand_a,
    input logic [7:0] operand_b,
    input logic [7:0] array_in [0:3],
    input logic       loop_en,
    output logic [7:0] op_result,
    output logic [7:0] loop_sum,
    output logic        status_flag
);
    logic [7:0] temp_val;
    always_comb begin
        temp_val = 8'h00;
        op_result = 8'h00;
        loop_sum = 8'h00;
        status_flag = 1'b0;
        if (select_op == 4'd0) begin
            op_result = operand_a + operand_b;
            status_flag = 1'b1;
        end else if (select_op == 4'd1) begin
            op_result = operand_a - operand_b;
        end else if (select_op == 4'd2) begin
            op_result = operand_a * operand_b;
        end else begin
            op_result = operand_a / (operand_b == 0 ? 1 : operand_b);
        end
        case (select_op)
            4'd0: temp_val = operand_a + 1;
            4'd1: temp_val = operand_a - 1;
            4'd2: temp_val = operand_b + 1;
            default: temp_val = operand_b - 1;
        endcase
        if (loop_en) begin
            for (int i = 0; i < 4; i = i + 1) begin
                loop_sum = loop_sum + array_in[i];
            end
        end
        if (loop_en && operand_a < 8) begin
            automatic int count = 0;
            while (count < operand_a) begin
                loop_sum = loop_sum + 1;
                count = count + 1;
            end
        end
        if (loop_en && operand_b > 4) begin
            repeat (2) begin
                loop_sum = loop_sum + 10;
            end
        end
        begin
            op_result = op_result + temp_val;
            if (op_result > 100) status_flag = 1'b0;
            else status_flag = 1'b1;
        end
    end
endmodule
module mod_data_types (
    input logic [15:0] in_val_a,
    input logic [15:0] in_val_b,
    input logic        mode_sel,
    output int         out_int,
    output real        out_real,
    output logic [1:0] out_enum,
    output logic [31:0] out_struct_val
);
    typedef enum logic [1:0] {
        IDLE = 2'b00,
        BUSY = 2'b01,
        DONE = 2'b10
    } state_t;
    typedef struct packed {
        logic [7:0] header;
        logic [15:0] payload;
        logic valid;
    } packet_t;
    state_t current_state;
    int integer_var;
    real real_var;
    packet_t my_packet;
    logic [31:0] wide_reg;
    always_comb begin
        integer_var = in_val_a + in_val_b;
        real_var = $itor(in_val_a) / $itor(in_val_b == 0 ? 1 : in_val_b);
        if (mode_sel) begin
            current_state = BUSY;
            my_packet.header = in_val_a[7:0];
            my_packet.payload = in_val_b;
            my_packet.valid = 1'b1;
        end else begin
            current_state = IDLE;
            my_packet.header = 8'hFF;
            my_packet.payload = 16'hFFFF;
            my_packet.valid = 1'b0;
        end
        wide_reg = {my_packet.valid, my_packet.header, my_packet.payload} + integer_var + 32'($rtoi(real_var));
        out_int = integer_var;
        out_real = real_var;
        out_enum = current_state;
        out_struct_val = wide_reg;
    end
endmodule
